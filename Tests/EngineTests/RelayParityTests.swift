import XCTest
@testable import GlucOSEngine

// The push relay runs on Supabase as a TypeScript edge function (supabase/functions/relay), so its
// alert rules, trend forecast and Live Activity card are a port of the Swift code here. This test
// keeps the two in step: it replays a set of scenarios through the Swift code, the same way the
// relay does on every fetch, and compares the result with `testdata/parity.json`. The edge
// function's tests replay the same file through the TypeScript code. Change either side and the
// other one's test fails until both agree again.
//
// After an intended change to the Swift side, regenerate the file and port the change:
//
//     GLUCOS_WRITE_PARITY=1 swift test --filter RelayParityTests

final class RelayParityTests: XCTestCase {
    static let fixtureURL = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .appendingPathComponent("supabase/functions/relay/testdata/parity.json")

    func testSwiftMatchesTheRelayParityFixtures() throws {
        let produced = ParityScenarios.all.map { $0.run() }
        let json: [String: Any] = [
            "note": "Generated by Tests/EngineTests/RelayParityTests.swift. Do not edit by hand.",
            "scenarios": produced,
        ]
        if ProcessInfo.processInfo.environment["GLUCOS_WRITE_PARITY"] == "1" {
            let data = try JSONSerialization.data(withJSONObject: json, options: [.sortedKeys])
            try FileManager.default.createDirectory(at: Self.fixtureURL.deletingLastPathComponent(),
                                                    withIntermediateDirectories: true)
            try data.write(to: Self.fixtureURL)
            return
        }
        let data = try Data(contentsOf: Self.fixtureURL)
        let stored = try JSONSerialization.jsonObject(with: data)
        // Round-trip what was produced so both sides are plain JSON values.
        let fresh = try JSONSerialization.jsonObject(with: JSONSerialization.data(withJSONObject: json))
        var problems: [String] = []
        ParityCompare.compare(stored, fresh, path: "$", into: &problems)
        XCTAssertTrue(problems.isEmpty, "Parity fixture is out of date. Regenerate it (see the comment at the top) "
                      + "and port the change to supabase/functions/relay:\n" + problems.prefix(20).joined(separator: "\n"))
    }
}

// MARK: - Scenarios

/// One run of the relay: ticks one minute (or so) apart, each with the readings LibreLinkUp
/// returned, through the same steps as the relay's tick.
struct ParityScenario {
    struct Tick {
        var now: Date
        /// What LibreLinkUp returned: history plus the current reading. Empty: the fetch failed.
        var history: [GlucoseReading]
        var current: GlucoseReading?
        var sensor: SensorInfo?
        var error: String?
        /// Relearn the forecast's accuracy before this tick, from everything stored so far.
        var learn = false
        /// Write this tick's result into the file. Warm-up ticks only build up state.
        var record = true
    }

    var name: String
    var unit: GlucoseUnit = .mmol
    var lowMgdl: Double = 70
    var highMgdl: Double = 180
    var prefs = AlertPreferences()
    var ticks: [Tick]

    func run() -> [String: Any] {
        var planner = AlertPlanner()
        var model = OutlookModel.empty
        var stored: [GlucoseReading] = []
        var current: GlucoseReading?
        var sensor: SensorInfo?
        var out: [[String: Any]] = []

        for t in ticks {
            if t.learn, stored.count > 24 {
                model = OutlookEngine.learn(readings: stored, doses: [], meals: [], contexts: [],
                                            low: lowMgdl, high: highMgdl, now: t.now)
            }
            var lastError: String?
            if let e = t.error {
                lastError = e
            } else {
                var byTime = Dictionary(stored.map { ($0.timestamp, $0) }, uniquingKeysWith: { a, _ in a })
                for r in t.history { byTime[r.timestamp] = r }
                if let c = t.current { byTime[c.timestamp] = c; current = c }
                let cutoff = t.now.addingTimeInterval(-48 * 3600)
                stored = byTime.values.filter { $0.timestamp >= cutoff }.sorted { $0.timestamp < $1.timestamp }
                if let s = t.sensor { sensor = s }
            }

            var snap = GlucoseSnapshot()
            snap.current = current
            if let current {
                let cutoff = current.timestamp.addingTimeInterval(-12 * 3600)
                snap.history = stored.filter { $0.timestamp >= cutoff && $0.timestamp < current.timestamp }
            }
            snap.sensor = sensor
            snap.unit = unit
            snap.lowMgdl = lowMgdl
            snap.highMgdl = highMgdl
            snap.fetchedAt = t.now
            snap.lastError = lastError

            let recent = stored.filter { t.now.timeIntervalSince($0.timestamp) <= 3600 }
            let outlook = OutlookEngine.outlook(readings: recent, doses: [], meals: [], contexts: [], model: model, now: t.now)
            if snap.current != nil { snap.outlook = outlook.snapshot(lowMgdl: lowMgdl) }

            var notices = planner.evaluate(snap, prefs: prefs, now: t.now)
            if let p = planner.evaluatePrediction(snap, forecast: outlook.glucoseForecast, prefs: prefs, now: t.now) {
                notices.append(p)
            }
            let card = GlucoseActivityState.make(from: snap, readings: stored, source: "relay", now: t.now)
            guard t.record else {
                out.append([:])
                continue
            }

            var row: [String: Any] = [
                "now": t.now.timeIntervalSince1970,
                "notices": notices.map { ["kind": $0.kind.rawValue, "title": $0.title, "body": $0.body, "critical": $0.critical] },
            ]
            switch outlook.forecast {
            case .success(let f):
                row["forecast"] = [
                    "basis": f.basis.rawValue,
                    "trendPerMinute": f.trendPerMinute,
                    "samples": f.samples.map { [$0.date.timeIntervalSince1970, $0.mgdl, $0.lowerMgdl, $0.upperMgdl] },
                ]
            case .failure(let e):
                row["forecastUnavailable"] = e.reason.message
            }
            if let card, let data = try? JSONEncoder().encode(card) {
                row["card"] = (try? JSONSerialization.jsonObject(with: data)) ?? NSNull()
            }
            out.append(row)
        }

        var scenario: [String: Any] = [
            "name": name,
            "unit": unit.rawValue,
            "lowMgdl": lowMgdl,
            "highMgdl": highMgdl,
            "prefs": [
                "enabled": prefs.enabled, "high": prefs.high, "rapidChange": prefs.rapidChange, "stale": prefs.stale,
                "sensorExpiry": prefs.sensorExpiry, "predictedLow": prefs.predictedLow,
                "predictedHigh": prefs.predictedHigh, "predictiveMinutes": prefs.predictiveMinutes,
                "cooldownMinutes": prefs.cooldownMinutes,
            ],
            "ticks": ticks.map { t -> [String: Any] in
                var d: [String: Any] = [
                    "now": t.now.timeIntervalSince1970,
                    "history": t.history.map { [$0.timestamp.timeIntervalSince1970, $0.mgdl, Double($0.trend.rawValue)] },
                    "learn": t.learn,
                    "record": t.record,
                ]
                if let c = t.current { d["current"] = [c.timestamp.timeIntervalSince1970, c.mgdl, Double(c.trend.rawValue)] }
                if let s = t.sensor {
                    d["sensor"] = ["serial": s.serial, "activated": s.activated.timeIntervalSince1970, "lifetimeDays": s.lifetimeDays]
                }
                if let e = t.error { d["error"] = e }
                return d
            },
            "expected": out,
        ]
        if let cal = model.calibration, let s = cal.stats(for: .trend) {
            scenario["calibration"] = s.map { ["minutes": $0.minutes, "samples": $0.samples, "lower": $0.lower, "upper": $0.upper,
                                               "mae": $0.meanAbsoluteError, "naive": $0.naiveError] }
        }
        return scenario
    }
}

enum ParityScenarios {
    static let t0 = Date(timeIntervalSince1970: 1_790_000_000)

    /// A deterministic jitter in -1...1, so noisy scenarios are the same every run.
    static func jitter(_ i: Int) -> Double {
        var x = UInt64(truncatingIfNeeded: i &* 2_654_435_761 &+ 97)
        x ^= x >> 13; x = x &* 0x5bd1e995; x ^= x >> 15
        return Double(x % 2001) / 1000 - 1
    }

    static func trendFor(_ slope: Double) -> Trend {
        switch slope {
        case ..<(-2): return .fallingQuickly
        case ..<(-1): return .falling
        case ...1: return .flat
        case ...2: return .rising
        default: return .risingQuickly
        }
    }

    /// Ticks every `every` seconds from `start` for `count` ticks. The curve gives mg/dL at a time
    /// offset in minutes from `start`. LibreLinkUp's history has a point every 15 minutes (5 here,
    /// to keep the files small and the card's sparkline filled); the current reading is a minute old.
    static func ticks(start: Date = t0, count: Int, every: TimeInterval = 60, historyMinutes: Int = 180,
                      gap: ClosedRange<Int>? = nil, curve: (Double) -> Double) -> [ParityScenario.Tick] {
        (0..<count).map { i in
            let now = start.addingTimeInterval(Double(i) * every)
            let readingAt = now.addingTimeInterval(-60)
            let m = readingAt.timeIntervalSince(start) / 60
            if let gap, gap.contains(i) {
                return .init(now: now, history: [], current: nil, sensor: nil, error: nil)
            }
            let slope = curve(m) - curve(m - 1)
            let current = GlucoseReading(timestamp: readingAt, mgdl: curve(m).rounded(), trend: trendFor(slope))
            // History on a 5-minute grid, ending before the current reading.
            let lastSlot = floor(readingAt.timeIntervalSince1970 / 300) * 300
            let history = stride(from: historyMinutes, through: 5, by: -5).compactMap { back -> GlucoseReading? in
                let at = Date(timeIntervalSince1970: lastSlot - Double(back - 5) * 60 - 300)
                guard at < readingAt else { return nil }
                return GlucoseReading(timestamp: at, mgdl: curve(at.timeIntervalSince(start) / 60).rounded(), trend: .unknown)
            }
            return .init(now: now, history: history, current: current, sensor: nil, error: nil)
        }
    }

    static var all: [ParityScenario] {
        var list: [ParityScenario] = []

        // Falling steadily through low into urgent low, mmol.
        list.append(.init(name: "falling-to-urgent-low", ticks: ticks(count: 40, every: 120) { m in 130 - 1.6 * m }))

        // Rising into high and very high, mg/dL, with the high alert on.
        list.append(.init(name: "rising-to-very-high-mgdl", unit: .mgdl,
                          ticks: ticks(count: 45, every: 120) { m in 140 + 2.4 * m }))

        // The same rise with high alerts off and a 30-minute predictive lead.
        var noHigh = AlertPreferences()
        noHigh.high = false
        noHigh.predictiveMinutes = 30
        noHigh.cooldownMinutes = 20
        list.append(.init(name: "rising-high-alerts-off", prefs: noHigh,
                          ticks: ticks(count: 30, every: 180) { m in 150 + 2.2 * m }))

        // Fast swings: rapid-change alerts and their reset.
        list.append(.init(name: "rapid-swings", lowMgdl: 72, highMgdl: 200,
                          ticks: ticks(count: 50, every: 60) { m in 140 + 60 * sin(m / 9) }))

        // Readings stop for 40 minutes (stale alert, no forecast, grey card), then come back.
        var gap = ticks(count: 70, every: 60, gap: 15...55) { m in 110 + 10 * sin(m / 20) }
        gap[60].error = "LibreLinkUp returned status 4."
        list.append(.init(name: "data-gap-and-error", ticks: gap))

        // Sensor about to expire, and the client version being refused.
        var sensorTicks = ticks(count: 8, every: 600) { m in 100 + m * 0.2 }
        for i in sensorTicks.indices {
            sensorTicks[i].sensor = SensorInfo(serial: "3MH00ABCD", activated: t0.addingTimeInterval(-14.6 * 86_400), lifetimeDays: 15)
        }
        sensorTicks[5].error = "Abbott now requires client version 4.17.0+. Update the version in Settings."
        list.append(.init(name: "sensor-expiry-and-version", ticks: sensorTicks))

        // Alerts switched off entirely.
        var off = AlertPreferences()
        off.enabled = false
        list.append(.init(name: "alerts-off", prefs: off, ticks: ticks(count: 10, every: 300) { m in 60 - m * 0.5 }))

        // Two noisy days, then the forecast's accuracy is learnt from them and sets the band and
        // how far ahead the forecast looks.
        let day: (Double) -> Double = { m in
            130 + 45 * sin(m / 70) + 20 * sin(m / 23 + 1) + 4 * jitter(Int(m.rounded()))
        }
        var warmup = ticks(start: t0, count: 2 * 24 * 12, every: 300, historyMinutes: 10, curve: day)
        for i in warmup.indices { warmup[i].record = false }
        var tail = ticks(start: t0.addingTimeInterval(2 * 86_400), count: 20, every: 60, historyMinutes: 10) { m in
            day(m + 2 * 24 * 60)
        }
        tail[0].learn = true
        list.append(.init(name: "learnt-calibration", ticks: warmup + tail))

        return list
    }
}

// MARK: - Comparing

enum ParityCompare {
    static func compare(_ a: Any, _ b: Any, path: String, into problems: inout [String]) {
        switch (a, b) {
        case let (x as [String: Any], y as [String: Any]):
            for k in Set(x.keys).union(y.keys).sorted() {
                guard let xv = x[k], let yv = y[k] else { problems.append("\(path).\(k): missing on one side"); continue }
                compare(xv, yv, path: "\(path).\(k)", into: &problems)
            }
        case let (x as [Any], y as [Any]):
            guard x.count == y.count else { problems.append("\(path): \(x.count) vs \(y.count) items"); return }
            for i in x.indices { compare(x[i], y[i], path: "\(path)[\(i)]", into: &problems) }
        case let (x as String, y as String):
            if x != y { problems.append("\(path): \"\(x)\" vs \"\(y)\"") }
        case let (x as NSNumber, y as NSNumber):
            // Booleans come back as NSNumber too.
            if abs(x.doubleValue - y.doubleValue) > 1e-6 * max(1, abs(x.doubleValue)) {
                problems.append("\(path): \(x) vs \(y)")
            }
        case (is NSNull, is NSNull):
            break
        default:
            problems.append("\(path): different types")
        }
    }
}
